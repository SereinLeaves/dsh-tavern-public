import {readFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
const code=await readFile(new URL('./scene-projection.fixture.js',import.meta.url),'utf8');
const {projectScene,namesInSceneHeader}=await import('data:text/javascript;base64,'+Buffer.from(code+'\nexport {projectScene,namesInSceneHeader};').toString('base64'));
const names=['甲角色','乙角色','丙角色','Mary Jane'];
const old={text:'【时间】清晨 【地点】咨询室 【在场人物】甲角色、用户角色\n她抬起头。',messageId:'one'};
const switched={text:'**【时间】周一 【地点】教室 【在场人物】乙角色、用户角色、其他学生**\n她抬起头说了一句话。',messageId:'two'};
let p=projectScene([old,switched],names,['甲角色']);
assert.equal(p.rows[0].name,'甲角色');
assert.equal(p.rows[1].name,'乙角色');
assert.deepEqual(p.presentNames,['乙角色']);
assert.deepEqual(p.activeNames,['乙角色']);
p=projectScene([old,switched,{text:'她继续说话。'}],names,['甲角色']);
assert.equal(p.rows[2].name,'乙角色');
const both={text:'【在场人物】乙角色、丙角色、用户角色\n两人进屋。',messageId:'three'};
p=projectScene([old,both],names,['甲角色']);
assert.equal(p.rows[1].name,'乙角色 · 丙角色');
assert.deepEqual(p.presentNames,['乙角色','丙角色']);
p=projectScene([both,{text:'丙角色：你好。'}],names,['甲角色']);
assert.deepEqual(p.activeNames,['丙角色']);
p=projectScene([old],names,['甲角色'],{afterMessageId:'one',names:['甲角色','乙角色'],activeName:'乙角色'});
assert.equal(p.rows[0].name,'甲角色');
assert.deepEqual(p.activeNames,['乙角色']);
assert.deepEqual(p.presentNames,['甲角色','乙角色']);
p=projectScene([old,switched],names,['甲角色'],{afterMessageId:'one',names:['甲角色','丙角色'],activeName:'丙角色'});
assert.deepEqual(p.activeNames,['乙角色']);
assert.deepEqual(projectScene([old],names,['甲角色'],{afterMessageId:'missing',names:['丙角色']}).activeNames,['甲角色']);
assert.equal(namesInSceneHeader('【在场人物】乙角色',names,true),null);
assert.deepEqual(namesInSceneHeader('【在场人物】乙角色\n',names,true),['乙角色']);
assert.equal(namesInSceneHeader('她想起乙角色曾经说过的话。',names),null);
assert.deepEqual(namesInSceneHeader('【在场人物】Mary Jane、用户角色',names),['Mary Jane']);
assert.deepEqual(projectScene([],names,['甲角色'],{names:['乙角色'],activeName:'乙角色'}).activeNames,['乙角色']);
p=projectScene([old,{kind:'user',text:'甲角色放一边，乙角色出场'}],names,['甲角色']);
assert.deepEqual(p.presentNames,['乙角色']);
assert.deepEqual(p.activeNames,['乙角色']);
p=projectScene([old,{kind:'user',text:'不要让乙角色出场'}],names,['甲角色']);
assert.deepEqual(p.presentNames,['甲角色']);
p=projectScene([old,{kind:'user',text:'我想起乙角色说过的那句话。'}],names,['甲角色']);
assert.deepEqual(p.presentNames,['甲角色']);
console.log('PASS historical speaker labels, typed scene switch, multiple characters, prefix speakers, portrait override ordering, stream completeness, no incidental-name switch, replay.');
